const ALERT_STATUS = new Set(['severe', 'overdue', 'urgent', 'stat', 'abnormal', 'no_show']);
function AlertMark() {
    return (_jsxs("svg", { viewBox: "0 0 16 16", "aria-hidden": true, className: "mr-1 inline h-3 w-3 shrink-0", fill: "none", stroke: "currentColor", strokeWidth: "1.75", children: [_jsx("path", { d: "M8 1.8 14.5 14H1.5L8 1.8z", strokeLinejoin: "round" }), _jsx("path", { d: "M8 6.2v3.4", strokeLinecap: "round" }), _jsx("path", { d: "M8 11.6h.01", strokeLinecap: "round" })] }));
}
export function statusLabel(value) {
    if (!value)
        return '';
    return LABELS[value] ?? value.replace(/_/g, ' ');
}
export function StatusBadge({ value }) {
    if (!value)
        return _jsx("span", { className: "text-gray-600", children: "\u2014" });
    return (_jsxs("span", { className: `${BASE} inline-flex items-center ${STATUS[value] ?? 'bg-gray-100 text-gray-700'}`, children: [ALERT_STATUS.has(value) ? _jsx(AlertMark, {}) : null, statusLabel(value)] }));
}
